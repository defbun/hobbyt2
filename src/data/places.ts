export function pluralPlaces(count: number) {
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 19) return 'мест';
  if (mod10 === 1) return 'место';
  if (mod10 >= 2 && mod10 <= 4) return 'места';
  return 'мест';
}
